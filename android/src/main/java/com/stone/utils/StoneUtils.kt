  fun resolveTransactionType(str: String): TypeOfTransactionEnum? {
    return when(str) {
      "debitCard" -> TypeOfTransactionEnum.DEBIT
      "creditCard" -> TypeOfTransactionEnum.CREDIT
      "voucher" -> TypeOfTransactionEnum.VOUCHER
      "pix" -> TypeOfTransactionEnum.PIX
      else -> null
    }
  }

