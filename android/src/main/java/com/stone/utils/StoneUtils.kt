  fun convertErrorsEnumToReadableArray(errors: List<ErrorsEnum>?, convertErrorToString: Boolean): ReadableArray {
    val writableArray = WritableNativeArray()
    errors?.forEach { error ->
      writableArray.pushString(
        if (convertErrorToString)
          resolveTransactionErrors(error)
        else error.name
      )
    }
    return writableArray
  }

